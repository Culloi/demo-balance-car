#ifndef OLED_FONT_H
#define OLED_FONT_H

#include <stdint.h>

/* Original 5x7 row patterns; oled.c scales them to 8x16 page data.
   Stage-one glyphs only: ' ', 'B', 'C', 'a', 'c', 'e', 'l', 'n', 'r'.
   Each row uses bits 4..0 from left to right. */
typedef struct
{
  char character;
  uint8_t rows[7];
} OLED_Glyph;

static const OLED_Glyph oled_glyphs[] = {
  {' ', {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00}},
  {'B', {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E}},
  {'C', {0x0F, 0x10, 0x10, 0x10, 0x10, 0x10, 0x0F}},
  {'a', {0x00, 0x00, 0x0E, 0x01, 0x0F, 0x11, 0x0F}},
  {'c', {0x00, 0x00, 0x0F, 0x10, 0x10, 0x10, 0x0F}},
  {'e', {0x00, 0x00, 0x0E, 0x11, 0x1F, 0x10, 0x0F}},
  {'l', {0x04, 0x04, 0x04, 0x04, 0x04, 0x04, 0x07}},
  {'n', {0x00, 0x00, 0x1E, 0x11, 0x11, 0x11, 0x11}},
  {'r', {0x00, 0x00, 0x16, 0x19, 0x10, 0x10, 0x10}}
};

#endif /* OLED_FONT_H */
